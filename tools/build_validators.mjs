// Compile every BIX schema into plain JavaScript validators (no `new Function` at runtime, so it runs on Hermes).
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";
const schemas = JSON.parse(readFileSync(new URL("../schemas/all.json", import.meta.url)));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
addFormats(ajv);
for (const s of schemas) ajv.addSchema(s);
const map = {};
for (const s of schemas) if (!s.$id.endsWith("datatypes.schema.json")) map[s.$id.replace(/^.*\/v0\.1\//, "").replace(".schema.json", "")] = s.$id;
let code = standaloneCode(ajv, map);
// ajv emits a couple of require() calls even in ESM mode; hoist them as imports.
const reqs = new Map();
code = code.replace(/require\("([^"]+)"\)/g, (_, m) => { if (!reqs.has(m)) reqs.set(m, `__r${reqs.size}`); return reqs.get(m); });
const imports = [...reqs].map(([m, n]) => `import * as ${n}_ns from "${m}.js"; const ${n} = ${n}_ns.default?.default ? ${n}_ns.default : ${n}_ns;`).join("\n");
writeFileSync(new URL("../schemas/validators.js", import.meta.url), "// Generated by bix/tools/build_validators.mjs. Do not edit.\n" + imports + "\n" + code.replace(/^"use strict";/, ""));
console.log(Object.keys(map).length, "validators written");
